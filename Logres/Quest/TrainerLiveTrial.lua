-- P0288: explicit, one-shot, read-only native trainer MODEL -> approved landscape.
-- This is not a trainer replacement. All Blizzard controls stay accessible.
local _, Logres = ...
local Trial = {}
Logres.NPCTrainerLiveTrial = Trial

local visual = Logres.PanelConfigs.trainer.preview
local panel = Logres.PanelConfigs.trainer
local placeholder = "Interface\\Icons\\INV_Misc_QuestionMark"
local active
local browse
local displays, deferrals = 0, 0
local last = "not-attempted"

local function bounded(value, max)
    return type(value) == "string" and #value > 0 and #value <= max
end

local function coin(copper)
    if type(copper) ~= "number" or copper < 0 or copper > 100000000000
        or copper ~= math.floor(copper) then
        return "?", "?", "?"
    end
    return tostring(math.floor(copper / 10000)),
        tostring(math.floor(copper / 100) % 100), tostring(copper % 100)
end

local function price(value)
    if type(value) ~= "number" or value < 0 or value > 100000000000
        or value ~= math.floor(value) then return "Cost unknown" end
    local g, s, c = coin(value)
    local parts = {}
    if g ~= "0" then parts[#parts + 1] = g .. "g" end
    if s ~= "0" then parts[#parts + 1] = s .. "s" end
    if c ~= "0" or #parts == 0 then parts[#parts + 1] = c .. "c" end
    return table.concat(parts, " ")
end

-- Pure conversion of *already secret-gated, addon-owned* probe results.
-- Forever six-field service types are descriptive only, never Train authorization.
function Trial.FromSnapshot(report)
    if type(report) ~= "table" or type(report.sample) ~= "table"
        or (report.status ~= "service-row-shape-deferred"
            and report.status ~= "read-only-service-sample") then
        return nil, "source-unavailable"
    end
    if #report.sample < 1 or #report.sample > 64 then
        return nil, "source-sample-size-deferred"
    end
    local rows, first, selected = {}, nil, nil
    local visibleNamed, visibleWithheld = 0, 0
    for i = 1, #report.sample do
        local native = report.sample[i]
        -- Indices are generated by the source probe, not taken from a
        -- filtered UI row. Refuse impossible/malformed identity outright.
        if type(native) ~= "table" or type(native.index) ~= "number"
            or native.index ~= math.floor(native.index)
            or native.index < 1 or native.index > 384 then
            return nil, "invalid-service-identity"
        end
        -- All four states are produced by the guarded source reader.
        -- The latter two are data deferrals, not unsafe trainer sessions.
        if native.state ~= "numeric-category-unclassified"
            and native.state ~= "source-observed"
            and native.state ~= "unexpected-service-shape"
            and native.state ~= "deferred-secret-or-call"
            and native.state ~= "forever-service-observed" then
            return nil, "unrecognized-service-source-state"
        end
        if i <= 64 then
            -- The probe returns native.name only after its ordinary() gate;
            -- a missing name becomes addon-owned explanatory placeholder text.
            local hasName = bounded(native.name, 100)
            local name = hasName and native.name
                or ("Service " .. tostring(native.index) .. " (details withheld)")
            if hasName and native.state == "forever-service-observed"
                and bounded(native.rank, 35) then
                local withRank = name .. " (" .. native.rank .. ")"
                if #withRank <= 100 then name = withRank end
            end
            local selectedRow = type(report.selected) == "number"
                and native.index == report.selected
            local recognized = native.state == "numeric-category-unclassified"
                or native.state == "source-observed"
                or native.state == "forever-service-observed"
            local requirement = "Availability not classified"
            if native.state == "forever-service-observed" then
                local parts = {}
                if type(native.requiredLevel) == "number" then
                    parts[#parts + 1] = "Level " .. tostring(native.requiredLevel)
                end
                if bounded(native.skillRequirement, 42) then
                    local skill = native.skillRequirement
                    if type(native.skillRank) == "number" then
                        skill = skill .. " (" .. tostring(native.skillRank) .. ")"
                    end
                    parts[#parts + 1] = skill
                end
                -- Genuine ability prerequisites (e.g. Wrath Rank 1) are
                -- independent from skill-rank and level requirements.
                if type(native.abilityRequirements) == "table" then
                    for slot = 1, math.min(#native.abilityRequirements, 4) do
                        local ability = native.abilityRequirements[slot]
                        if bounded(ability, 42) then
                            parts[#parts + 1] = ability
                        end
                    end
                end
                local requirements = table.concat(parts, " / ")
                if #requirements > 0 and #requirements <= 66 then
                    requirement = "Requires: " .. requirements
                end
                -- Source service-type strings describe Blizzard presentation;
                -- they never authorize buying, filtering or selecting.
                local label = nil
                if native.serviceType == "available" then label = "Available"
                elseif native.serviceType == "unavailable" then label = "Unavailable"
                elseif native.serviceType == "used" then label = "Known" end
                if label then
                    local combined = label
                    if requirement ~= "Availability not classified" then
                        combined = label .. " | " .. requirement
                    end
                    if #combined <= 90 then requirement = combined
                    else requirement = label end
                end
            end
            local texture = native.state == "forever-service-observed"
                and type(native.textureID) == "number" and native.textureID or placeholder
            local row = {serviceIndex=native.index, name=name,
                requirement="Availability not classified",
                price=recognized and price(native.cost) or "Cost unknown",
                icon=texture, selected=selectedRow, disabled=false,
                sourceType=native.state == "forever-service-observed" and native.serviceType or nil,
                description=recognized and native.description or nil,
                -- These already secret-gated source copies are only used for
                -- click-time live verification, never cached authorization.
                sourceName=hasName and native.name or nil,
                sourceRank=type(native.rank) == "string" and native.rank or "",
                sourceTextureID=native.textureID,
                sourceRequiredLevel=native.requiredLevel,
                costCopper=type(native.cost) == "number" and native.cost or nil}
            row.requirement = requirement
            rows[#rows + 1] = row
            if hasName then visibleNamed = visibleNamed + 1
            else visibleWithheld = visibleWithheld + 1 end
            if not first then first = row end
            if selectedRow then selected = row end
        end
    end
    if not first then return nil, "no-readable-services" end
    local catalog = rows
    rows = {}
    for i = 1, math.min(#catalog, panel.landscape.maxRows) do
        rows[i] = catalog[i]
    end
    local g, s, c = coin(report.wallet)
    local model = {
        title=bounded(report.trainerName, 90) and report.trainerName or "Trainer services",
        subtitle="LIVE SOURCE  /  BLIZZARD TRANSACTIONS",
        search="Search spells...",
        filters={label="Filters", mode="All sampled", categorized=false},
        funds={label="Funds", gold=g, silver=s, copper=c},
        trainAll={label="Train All unavailable", enabled=false},
        categories={"Sampled skills"}, activeCategory=1,
        profession="Sampled: " .. tostring(#catalog) .. " | showing 1-" .. tostring(#rows),
        rows=rows, catalog=catalog, localBrowse=true,
        nativeSession={total=report.total, trainerName=report.trainerName},
        selected={name=selected and selected.name or "Selection outside view",
            requirement=selected and selected.requirement or "Availability not classified",
            description=selected and bounded(selected.description, 260) and selected.description
                or "Live training details are read-only. Use Blizzard's trainer to filter, select or train.",
            icon=selected and selected.icon or placeholder},
        reagents={}, trainLabel="Stock Train", trainEnabled=false,
        footnote="LIVE READ-ONLY  /  SELECT LOCALLY / TRAIN IN BLIZZARD",
    }
    if not Logres.NPCTrainerLandscape.Build(model) then
        return nil, "landscape-model-rejected"
    end
    return model, visibleWithheld > 0 and "native-snapshot-mapped-partial" or "native-snapshot-mapped"
end

function Trial.Disable(why)
    if browse and browse.searchEdit then browse.searchEdit:ClearFocus() end
    browse = nil
    if active then active:Hide(); active = nil end
    last = why or "trial-hidden"
    return true, last
end

