local function ordinaryInput(value)
    if type(issecretvalue) ~= "function" then return false end
    local ok, secret = pcall(issecretvalue, value)
    return ok and secret == false
end

-- Reuse seven addon-owned row widgets; the snapshot is never reread by
-- mouse events. All/Available are LOCAL display filters only, and cannot
-- restore rows omitted by Blizzard's current native filter configuration.
local function refreshBrowse()
    if not browse or not active or not active:IsShown() then return false end
    local model = browse.model
    local matching = {}
    for _, row in ipairs(model.catalog) do
        -- Selection belongs to a captured native service identity, not a
        -- filtered or recycled display slot. Hidden selection remains local.
        row.selected = row.serviceIndex == browse.selectedServiceIndex
        if (not browse.availableOnly or row.sourceType == "available")
            and (browse.searchQuery == "" or
                string.find(row.name:lower(), browse.searchQuery, 1, true)) then
            matching[#matching + 1] = row
        end
    end
    local width = panel.landscape.maxRows
    local lastStart = math.max(1, #matching - width + 1)
    browse.offset = math.max(1, math.min(browse.offset, lastStart))
    local rows = {}
    for i = browse.offset, math.min(#matching, browse.offset + width - 1) do
        rows[#rows + 1] = matching[i]
    end
    if #rows == 0 then
        rows[1] = {name="No matching sampled skills",
            requirement="Clear search or try All sampled",
            price="", icon=placeholder, selected=false, disabled=true}
    end
    model.rows = rows
    local trainable = false
    if browse.localChoiceConfirmed then
        for _, entry in ipairs(matching) do
            if entry.serviceIndex == browse.selectedServiceIndex
                and entry.sourceType == "available" then
                trainable = true
                break
            end
        end
    end
    model.trainEnabled = trainable
    model.trainLabel = trainable and "Train selected (TEST)" or "Stock Train"
    model.filters.mode = browse.availableOnly and "Available only" or "All sampled"
    local finish = #matching == 0 and 0 or math.min(#matching, browse.offset + width - 1)
    model.profession = "Sampled " .. tostring(#model.catalog) .. " | "
        .. tostring(#matching) .. " match | " .. tostring(#matching == 0 and 0 or browse.offset)
        .. "-" .. tostring(finish)
    if not Logres.NPCTrainerLandscape.UpdateLiveRows(browse.controls, model) then
        return false
    end
    -- Keep the live thumb synchronized with wheel, arrows, filtering and drag.
    if browse.scrollSlider then
        browse.syncSlider = true
        browse.scrollSlider:SetMinMaxValues(1, lastStart)
        browse.scrollSlider:SetValue(browse.offset)
        if lastStart > 1 then
            local railLength = panel.landscape.geometry.list.h - 72
            local thumbHeight = math.max(18, math.floor(railLength * width / #matching))
            browse.scrollThumb:SetSize(8, math.min(railLength, thumbHeight))
            browse.scrollSlider:Show()
        else
            browse.scrollSlider:Hide()
        end
        browse.syncSlider = false
    end
    -- Empty-state copy is not a skill; never leave an invisible hit region.
    for i, hit in ipairs(browse.rowHits or {}) do
        if rows[i] and not rows[i].disabled and rows[i].serviceIndex then
            hit:Show()
        else
            hit:Hide()
        end
    end
    return true
end

-- This controller never calls a Blizzard service selector. Slot index is
-- resolved into a copied catalogue service identity at the moment of click.
local function selectLocalRow(position)
    if not browse or not active or not active:IsShown() then return end
    local row = browse.model.rows[position]
    if not row or row.disabled or type(row.serviceIndex) ~= "number" then return end
    local chosen
    for _, entry in ipairs(browse.model.catalog) do
        if entry.serviceIndex == row.serviceIndex then
            chosen = entry
            break
        end
    end
    if not chosen then return end
    browse.selectedServiceIndex = chosen.serviceIndex
    browse.localChoiceConfirmed = true
    for _, entry in ipairs(browse.model.catalog) do
        entry.selected = entry.serviceIndex == chosen.serviceIndex
    end
    browse.model.selected = {
        name=chosen.name, requirement=chosen.requirement,
        description=bounded(chosen.description, 260) and chosen.description
            or "No additional description supplied by this trainer.",
        icon=chosen.icon,
    }
    refreshBrowse()
end

local function moveBrowse(delta)
    if not browse or type(delta) ~= "number" then return end
    browse.offset = browse.offset + delta
    refreshBrowse()
end

local function attachBrowseControls(root, model, controls)
    local geometry = panel.landscape.geometry
    local initiallySelected
    for _, row in ipairs(model.catalog) do
        if row.selected then initiallySelected = row.serviceIndex; break end
    end
    browse = {model=model, controls=controls, offset=1, availableOnly=false,
        selectedServiceIndex=initiallySelected, rowHits={}, searchQuery="",
        localChoiceConfirmed=false}
    -- These children alone receive pointer input; the underlying approved
    -- landscape and all Blizzard controls remain without Logres actions.
    -- P0300: match the Quest Goodbye header affordance, not native closing.
    -- The owned live root and its children disappear through Trial.Disable.
    local goodbye = CreateFrame("Frame", nil, root)
    goodbye:SetSize(78, 24)
    goodbye:SetPoint("TOPRIGHT", root, "TOPRIGHT", -45, -12)
    goodbye:SetFrameLevel(root:GetFrameLevel() + 10)
    goodbye:EnableMouse(true)
    local goodbyeText = goodbye:CreateFontString(nil, "OVERLAY", "GameFontHighlightSmall")
    goodbyeText:SetAllPoints(goodbye)
    goodbyeText:SetText("Goodbye")
    goodbyeText:SetTextColor(0.97, 0.78, 0.44, 1)
    local goodbyeLine = goodbye:CreateTexture(nil, "ARTWORK")
    goodbyeLine:SetTexture("Interface\\Buttons\\WHITE8x8")
    goodbyeLine:SetHeight(1)
    goodbyeLine:SetPoint("BOTTOMLEFT", goodbye, "BOTTOMLEFT", 5, 0)
    goodbyeLine:SetPoint("BOTTOMRIGHT", goodbye, "BOTTOMRIGHT", -5, 0)
    goodbyeLine:SetVertexColor(0.77, 0.60, 0.32, 0.72)
    goodbye:SetScript("OnEnter", function()
        if active == root then goodbyeText:SetTextColor(1.00, 0.87, 0.56, 1) end
    end)
    goodbye:SetScript("OnLeave", function()
        goodbyeText:SetTextColor(0.97, 0.78, 0.44, 1)
    end)
    goodbye:SetScript("OnMouseUp", function(_, button)
        if ordinaryInput(button) and button == "LeftButton" and active == root then
            Trial.Disable("goodbye")
        end
    end)
    -- P0299: live-only keyboard field over the existing search art.
    -- Restricted to the left segment; never overlaps the owned Filters hitbox.
    local searchEdit = CreateFrame("EditBox", nil, root)
    searchEdit:SetPoint("TOPLEFT", root, "TOPLEFT",
        geometry.search.x + 11, -(geometry.search.y + 3))
    searchEdit:SetSize(geometry.filters.x - geometry.search.x - 18,
        geometry.search.h - 6)
    searchEdit:EnableMouse(true)
    searchEdit:SetFrameLevel(root:GetFrameLevel() + 8)
    searchEdit:SetFontObject("GameFontHighlightSmall")
    searchEdit:SetTextColor(0.94, 0.84, 0.68, 1)
    searchEdit:SetAutoFocus(false)
    searchEdit:SetMaxLetters(48)
    searchEdit:SetText("")
    searchEdit:SetScript("OnTextChanged", function(self)
        if not browse or active ~= root then return end
        local ok, value = pcall(function() return self:GetText() end)
        if not ok or not ordinaryInput(value) or type(value) ~= "string"
            or #value > 48 then return end
        browse.controls.searchHint:SetText("")
        local query = string.lower(value)
        if query == browse.searchQuery then return end
        browse.searchQuery = query
        browse.offset = 1
        refreshBrowse()
    end)
    searchEdit:SetScript("OnEditFocusGained", function()
        if browse and active == root then browse.controls.searchHint:SetText("") end
    end)
    searchEdit:SetScript("OnEditFocusLost", function(self)
        if not browse or active ~= root then return end
        local ok, value = pcall(function() return self:GetText() end)
        if ok and ordinaryInput(value) and type(value) == "string"
            and #value == 0 then
            browse.controls.searchHint:SetText("Search spells...")
        end
    end)
    searchEdit:SetScript("OnEscapePressed", function(self) self:ClearFocus() end)
    searchEdit:SetScript("OnEnterPressed", function(self) self:ClearFocus() end)
    browse.searchEdit = searchEdit
    local filter = CreateFrame("Frame", nil, root)
    filter:SetPoint("TOPLEFT", root, "TOPLEFT", geometry.filters.x, -geometry.filters.y)
    filter:SetSize(geometry.filters.w, geometry.filters.h)
    filter:EnableMouse(true)
    filter:SetScript("OnMouseUp", function(_, button)
        if not ordinaryInput(button) or button ~= "LeftButton"
            or active ~= root or not browse then return end
        browse.availableOnly = not browse.availableOnly
        browse.offset = 1
        refreshBrowse()
    end)
    local wheel = CreateFrame("Frame", nil, root)
    wheel:SetPoint("TOPLEFT", root, "TOPLEFT", geometry.list.x + 8, -(geometry.list.y + 7))
    wheel:SetSize(geometry.list.w - 45, geometry.list.h - 14)
    -- Explicit input stack: inert row paint is below the wheel; the seven
    -- clickable skill regions are children above it. Same owned list bounds.
    wheel:SetFrameLevel(root:GetFrameLevel() + 4)
    wheel:EnableMouse(true)
    wheel:EnableMouseWheel(true)
    wheel:SetScript("OnMouseWheel", function(_, delta)
        if active == root and browse and ordinaryInput(delta)
            and type(delta) == "number" and delta ~= 0 then
            moveBrowse(delta > 0 and -1 or 1)
        end
    end)
    for _, arrow in ipairs({{glyph="^", y=geometry.list.y + 7, step=-7},
                             {glyph="v", y=geometry.list.y + geometry.list.h - 29, step=7}}) do
        local step = arrow.step
        local control = CreateFrame("Frame", nil, root)
        control:SetPoint("TOPLEFT", root, "TOPLEFT", geometry.list.x + geometry.list.w - 28, -arrow.y)
        control:SetSize(22, 22)
        control:EnableMouse(true)
        control:SetScript("OnMouseUp", function(_, button)
            if ordinaryInput(button) and button == "LeftButton" and active == root then
                moveBrowse(step)
            end
        end)
        local label = control:CreateFontString(nil, "OVERLAY", "GameFontNormal")
        label:SetAllPoints(control)
        label:SetText(arrow.glyph)
    end
    -- P0296: actual LIVE slider. The accepted synthetic preview still
    -- paints an inert gold thumb; the source controller owns drag and track.
    local rail = CreateFrame("Slider", nil, root)
    rail:SetPoint("TOPLEFT", root, "TOPLEFT", geometry.list.x + geometry.list.w - 26,
        -(geometry.list.y + 36))
    rail:SetSize(20, geometry.list.h - 72)
    rail:SetOrientation("VERTICAL")
    rail:SetFrameLevel(wheel:GetFrameLevel() + 4)
    rail:SetMinMaxValues(1, 1)
    rail:SetValueStep(1)
    rail:SetThumbTexture("Interface\Buttons\WHITE8x8")
    local thumb = rail:GetThumbTexture()
    thumb:SetVertexColor(0.82, 0.59, 0.25, 0.95)
    thumb:SetSize(8, 24)
    rail:SetScript("OnValueChanged", function(_, value)
        if not browse or browse.syncSlider or active ~= root
            or not ordinaryInput(value) or type(value) ~= "number" then return end
        local newOffset = math.floor(value + 0.5)
        if newOffset ~= browse.offset then
            browse.offset = newOffset
            refreshBrowse()
        end
    end)
    rail:EnableMouseWheel(true)
    rail:SetScript("OnMouseWheel", function(_, delta)
        if active == root and browse and ordinaryInput(delta)
            and type(delta) == "number" and delta ~= 0 then
            moveBrowse(delta > 0 and -1 or 1)
        end
    end)
    browse.scrollSlider = rail
    browse.scrollThumb = thumb
    -- Draw only over the seven named catalogue rows. Each region handles
    -- wheel input too, so the existing list scroll is not lost on hover.
    for i = 1, panel.landscape.maxRows do
        local position = i
        -- A wheel sibling can otherwise claim mouse focus before
        -- transparent row hits. Parent each hit to the wheel and order it
        -- explicitly above the wheel's own mouse surface.
        local hit = CreateFrame("Frame", nil, wheel)
        hit:SetPoint("TOPLEFT", root, "TOPLEFT", geometry.list.x + 8,
            -(geometry.list.y + geometry.list.top + (i - 1) * geometry.list.pitch))
        hit:SetSize(geometry.list.w - 45, geometry.list.rowHeight)
        hit:SetFrameLevel(wheel:GetFrameLevel() + 2)
        hit:EnableMouse(true)
        hit:EnableMouseWheel(true)
        hit:SetScript("OnMouseUp", function(_, button)
            if active == root and browse and ordinaryInput(button)
                and button == "LeftButton" then selectLocalRow(position) end
        end)
        hit:SetScript("OnMouseWheel", function(_, delta)
            if active == root and browse and ordinaryInput(delta)
                and type(delta) == "number" and delta ~= 0 then
                moveBrowse(delta > 0 and -1 or 1)
            end
        end)
        browse.rowHits[i] = hit
    end
    -- A deliberate physical click: never train on local row selection itself.
    local trainHit = CreateFrame("Frame", nil, root)
    trainHit:SetPoint("TOPLEFT", root, "TOPLEFT", geometry.train.x, -geometry.train.y)
    trainHit:SetSize(geometry.train.w, geometry.train.h)
    trainHit:SetFrameLevel(wheel:GetFrameLevel() + 2)
    trainHit:EnableMouse(true)
    trainHit:SetScript("OnMouseUp", function(_, button)
        if not ordinaryInput(button) or button ~= "LeftButton" or active ~= root
            or not browse or not browse.localChoiceConfirmed
            or not browse.model.trainEnabled then return end
        local chosen
        for _, entry in ipairs(browse.model.catalog) do
            if entry.serviceIndex == browse.selectedServiceIndex then
                chosen = entry
                break
            end
        end
        if not chosen or not Logres.NPCTrainerPurchaseTrial then return end
        local accepted, reason = Logres.NPCTrainerPurchaseTrial.Attempt(
            chosen, browse.model.nativeSession)
        if accepted then
            -- Stock remains accessible; this sample is stale after a buy request.
            Trial.Disable("native-purchase-requested-unconfirmed")
        else
            last = "native-purchase-deferred-" .. tostring(reason)
        end
    end)
end

function Trial.Toggle(mode)
    if mode == "off" or (mode == nil and active and active:IsShown()) then
        return Trial.Disable("trial-hidden")
    end
    if mode ~= nil and mode ~= "on" then return false, "use-on-or-off" end
    -- Probe.Read enforces trainer-open, ordinary native root, and out-of-combat.
    local report = Logres.NPCNativeTrainerServiceProbe.Read()
    local model, why = Trial.FromSnapshot(report)
    if not model then
        deferrals = deferrals + 1
        last = why
        return false, why
    end
    -- A fresh addon-owned panel prevents stale rows after native filter changes.
    -- It is mouse-inert; all Blizzard-native selection/training remains available.
    local ok, owner, controls = pcall(function()
        local root = CreateFrame("Frame", nil, UIParent)
        root:SetSize(visual.width, visual.height)
        root:SetPoint(visual.point, UIParent, visual.relativePoint, visual.x, visual.y)
        root:SetFrameStrata(visual.strata)
        root:EnableMouse(false)
        root:Hide()
        if not Logres.PanelSurface.Paint(root, panel.surface, visual.width, visual.height) then
            error("live-panel-art-unavailable")
        end
        local rendered, _, controls = Logres.NPCTrainerLandscape.Render(root, model)
        if not rendered then error("live-landscape-render-deferred") end
        return root, controls
    end)
    if not ok or not owner then
        deferrals = deferrals + 1
        last = "addon-owned-render-deferred"
        return false, last
    end
    if active then active:Hide() end
    active = owner
    local attached = pcall(attachBrowseControls, owner, model, controls)
    if not attached then
        Trial.Disable("local-input-deferred")
        deferrals = deferrals + 1
        return false, last
    end
    owner:Show()
    if not refreshBrowse() then
        Trial.Disable("local-view-update-deferred")
        deferrals = deferrals + 1
        return false, last
    end
    displays = displays + 1
    last = why == "native-snapshot-mapped-partial" and "live-partial-visible" or "live-read-only-visible"
    return true, last
end

function Trial.GetAudit()
    return {shown=active and active:IsShown() or false,
        displays=displays, deferrals=deferrals, last=last,
        purchases=0, filterWrites=0, selectionWrites=0, nativeGeometryWrites=0,
        purchaseTrial=Logres.NPCTrainerPurchaseTrial.GetAudit()}
end

return Trial
